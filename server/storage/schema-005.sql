CREATE TABLE IF NOT EXISTS metatft_query_snapshots (
  id CHAR(64) PRIMARY KEY,
  release_id CHAR(64) NOT NULL,
  query_key CHAR(64) NOT NULL,
  season INT NOT NULL,
  requested_patch VARCHAR(24) NOT NULL,
  requested_b_patch VARCHAR(12) NOT NULL,
  query_scope JSON NOT NULL,
  source_metadata JSON NOT NULL,
  raw_responses JSON NOT NULL,
  content_hash CHAR(64) NOT NULL,
  summary JSON NOT NULL,
  captured_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL,
  INDEX metatft_query_lookup(release_id,query_key,captured_at),
  FOREIGN KEY(release_id) REFERENCES data_releases(id)
) ENGINE=InnoDB;
CREATE TABLE IF NOT EXISTS metatft_query_rows (
  snapshot_id CHAR(64) NOT NULL,
  dimension VARCHAR(24) NOT NULL,
  row_key CHAR(64) NOT NULL,
  champion_id VARCHAR(240) NULL,
  item_ids JSON NOT NULL,
  unit_ids JSON NOT NULL,
  placement_count JSON NOT NULL,
  sample_size BIGINT NOT NULL,
  avg_placement DOUBLE NOT NULL,
  top4_rate DOUBLE NOT NULL,
  win_rate DOUBLE NOT NULL,
  payload JSON NOT NULL,
  PRIMARY KEY(snapshot_id,dimension,row_key),
  INDEX metatft_rows_samples(snapshot_id,dimension,sample_size),
  INDEX metatft_rows_champion(snapshot_id,dimension,champion_id),
  FOREIGN KEY(snapshot_id) REFERENCES metatft_query_snapshots(id)
) ENGINE=InnoDB;
