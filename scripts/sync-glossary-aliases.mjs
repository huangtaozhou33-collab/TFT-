import { readFileSync, writeFileSync } from 'node:fs';
// Offline generation only. Do not infer canonical names, IDs, costs or traits.
const dataset=JSON.parse(readFileSync(new URL('../data/glossary/zh-CN.v4.json',import.meta.url),'utf8'));
const aliases={};
for(const entry of dataset.entries) {
  if(entry.canonicalEntity?.type!=='champion')continue;
  const name=entry.canonicalEntity.name;
  aliases[name]=[...new Set([...(aliases[name]??[]),entry.term,...entry.aliases])];
}
const output='// Generated by scripts/sync-glossary-aliases.mjs from the supplied hero readings.\n// Names attach only to existing catalog rows; they do not establish season availability.\nexport const COMMUNITY_CHAMPION_ALIASES = '+JSON.stringify(aliases,null,2)+';\n';
writeFileSync(new URL('../public/glossary-aliases.js',import.meta.url),output);
console.log(`Updated ${Object.keys(aliases).length} hero name mappings; no provider calls.`);
